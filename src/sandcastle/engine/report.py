def _inject_charts(html: str, metadata: dict[str, Any]) -> str:
    """Find data patterns in the content and replace with rendered chart images.

    Looks for fenced code blocks with language ``chart`` or ``data`` and
    attempts to render them as matplotlib figures encoded as base64 PNG.
    """
    if not HAS_MATPLOTLIB:
        return html

    chart_pattern = re.compile(
        r'<pre><code class="language-chart">(.*?)</code></pre>',
        re.DOTALL,
    )

    def _render_chart(m: re.Match) -> str:
        spec = m.group(1).strip()
        try:
            import json

            data = json.loads(spec)
            chart_type = data.get("type", "bar")
            labels = data.get("labels", [])
            values = data.get("values", [])
            title = data.get("title", "")
            accent = metadata.get("accent_color", "#f59e0b")

            fig, ax = plt.subplots(figsize=(6, 3.5), dpi=150)
            fig.patch.set_facecolor("white")

            if chart_type == "pie" and labels and values:
                colors = _generate_palette(accent, len(labels))
                ax.pie(values, labels=labels, colors=colors, autopct="%1.1f%%",
                       startangle=90, textprops={"fontsize": 8})
            elif chart_type == "line" and values:
                ax.plot(labels or list(range(len(values))), values,
                        color=accent, linewidth=2, marker="o", markersize=4)
                ax.grid(True, alpha=0.3)
            else:
                # Default bar chart
                colors = _generate_palette(accent, len(values))
                bars = ax.bar(labels or list(range(len(values))), values, color=colors)
                ax.grid(True, axis="y", alpha=0.3)

            if title:
                ax.set_title(title, fontsize=11, fontweight="bold", pad=10)
            ax.spines["top"].set_visible(False)
            ax.spines["right"].set_visible(False)
            fig.tight_layout()

            buf = io.BytesIO()
            fig.savefig(buf, format="png", bbox_inches="tight", facecolor="white")
            plt.close(fig)
            buf.seek(0)
            b64 = base64.b64encode(buf.read()).decode()
            return (
                f'<div class="chart-container">'
                f'<img src="data:image/png;base64,{b64}" alt="{title}">'
                f"</div>"
            )
        except Exception as exc:
            logger.warning("Chart rendering failed: %s", exc)
            return m.group(0)  # Keep original on failure

    return chart_pattern.sub(_render_chart, html)


def _generate_palette(accent: str, n: int) -> list[str]:
    """Generate n colors as tints/shades of the accent color.

    Creates a cohesive monochromatic palette instead of random colors.
    Lighter tints for less important items, darker for emphasis.
    """
    # Parse accent hex color
    acc = accent.lstrip("#")
    try:
        r, g, b = int(acc[:2], 16), int(acc[2:4], 16), int(acc[4:6], 16)
    except (ValueError, IndexError):
        r, g, b = 59, 130, 246  # fallback blue

    colors = []
    for i in range(n):
        # Vary lightness: from 30% darker to 60% lighter
        t = i / max(n - 1, 1)  # 0.0 to 1.0
        factor = 0.7 + t * 0.9  # 0.7 (darker) to 1.6 (lighter)
        nr = min(255, int(r * factor))
        ng = min(255, int(g * factor))
        nb = min(255, int(b * factor))
        colors.append(f"#{nr:02x}{ng:02x}{nb:02x}")

    return colors


