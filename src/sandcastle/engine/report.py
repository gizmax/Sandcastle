def _build_toc(html: str) -> tuple[str, str]:
    """Extract h2/h3 headings from HTML and build a ToC block.

    Returns (toc_html, modified_html_with_ids).
    """
    heading_pattern = re.compile(r"<(h[23])(?:\s[^>]*)?>(.+?)</\1>", re.IGNORECASE)
    entries: list[tuple[str, str, str]] = []  # (level, id, text)
    counter = 0

    def _add_id(m: re.Match) -> str:
        nonlocal counter
        tag = m.group(1).lower()
        text = re.sub(r"<[^>]+>", "", m.group(2)).strip()
        anchor = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
        if not anchor:
            anchor = f"section-{counter}"
        anchor = f"{anchor}-{counter}"
        counter += 1
        entries.append((tag, anchor, text))
        return f'<{tag} id="{anchor}">{m.group(2)}</{tag}>'

    modified_html = heading_pattern.sub(_add_id, html)

    if not entries:
        return "", modified_html

    toc_lines = ['<div class="toc">', "<h2>Table of Contents</h2>", "<ul>"]
    for level, anchor, text in entries:
        css_class = "toc-h3" if level == "h3" else "toc-h2"
        toc_lines.append(
            f'<li class="{css_class}">'
            f'<a href="#{anchor}">{text}<span class="dots"></span>'
            f'</a>'
            f"</li>"
        )
    toc_lines.append("</ul>")
    toc_lines.append("</div>")

    return "\n".join(toc_lines), modified_html


