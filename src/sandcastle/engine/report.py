def render_report(
    content: str,
    config: Any,  # ReportConfig (imported as Any to avoid circular imports)
    metadata: dict[str, Any] | None = None,
) -> bytes:
    """Render Markdown content into PDF bytes using WeasyPrint + Jinja2.

    Args:
        content: Markdown text (typically LLM output).
        config: A ReportConfig dataclass instance.
        metadata: Optional extra metadata dict (e.g. run_id, step_id).

    Returns:
        PDF file content as bytes.

    Raises:
        RuntimeError: If weasyprint is not installed.
    """
    if not HAS_WEASYPRINT:
        raise RuntimeError(
            "weasyprint is not installed. Install with: pip install sandcastle-ai[report]"
        )

    metadata = metadata or {}
    now = datetime.now(timezone.utc)
    accent = _safe_accent(config.accent_color)

    # 1. Preprocess raw markdown
    content = _preprocess_markdown(content)

    # 2. Convert markdown to HTML
    body_html = _markdown_to_html(content)

    # 3. Auto-generate charts from tables with numeric data
    body_html = _auto_charts_from_tables(body_html, accent)

    # 4. Parse explicit ```chart``` code blocks
    body_html = _parse_chart_blocks(body_html, accent)

    # 5. Legacy chart injection (JSON format)
    body_html = _inject_charts(body_html, {"accent_color": accent, **metadata})

    # 6. Parse :::metric KPI rows
    body_html = _parse_metric_rows(body_html)

    # 7. Parse :::info / :::warning / :::success callout boxes
    body_html = _parse_callout_boxes(body_html)

    # 8. Parse ---{text}--- styled dividers
    body_html = _parse_dividers(body_html)

    # 9. Build table of contents
    toc_html = ""
    if config.include_toc:
        toc_html, body_html = _build_toc(body_html)

    # Format CSS
    css = _format_css(config.theme, accent, config.paper_size,
                      config.include_page_numbers)

    # Cover page elements - HTML-escape all user/config supplied strings to
    # prevent stored XSS / HTML injection through ReportConfig fields.
    raw_title = config.title or metadata.get("title", "Report")
    title = _html.escape(str(raw_title))
    subtitle_html = (
        f'<div class="subtitle">{_html.escape(str(config.subtitle))}</div>'
        if config.subtitle else ""
    )
    author_html = (
        f"<div><strong>Author:</strong> {_html.escape(str(config.author))}</div>"
        if config.author else ""
    )
    # Only embed the logo when it points at a safe http(s) host or is a
    # data: URI; otherwise drop it to avoid SSRF/file:// access via WeasyPrint.
    logo_html = ""
    if config.logo_url:
        logo_src = str(config.logo_url)
        if logo_src.startswith("data:") or _is_safe_remote_url(logo_src):
            logo_html = (
                f'<img class="logo" src="{_html.escape(logo_src, quote=True)}" '
                f'alt="Logo">'
            )
        else:
            logger.warning(
                "Refusing to embed logo from unsafe URL: %s", logo_src[:120],
            )
    date_str = now.strftime("%B %d, %Y")

    # Apply Jinja2 template if available, otherwise simple string formatting
    full_html = _REPORT_HTML_TEMPLATE.format(
        css=css,
        logo_html=logo_html,
        title=title,
        subtitle_html=subtitle_html,
        author_html=author_html,
        date=date_str,
        toc_html=toc_html,
        content=body_html,
    )

    # Render to PDF via WeasyPrint
    if config.format == "html":
        return full_html.encode("utf-8")

    # Restrict resource fetching to safe http(s) URLs / data: URIs.
    pdf_bytes = WeasyprintHTML(
        string=full_html, url_fetcher=_safe_url_fetcher,
    ).write_pdf()
    return pdf_bytes


