def _render_chart_image(
    chart_type: str,
    labels: list[str],
    values: list[float],
    title: str,
    accent: str,
) -> str:
    """Render a matplotlib chart and return a base64-encoded PNG data URI.

    Supported chart_type values: bar, horizontal_bar, pie, line.
    Returns empty string if matplotlib is unavailable or rendering fails.
    """
    if not HAS_MATPLOTLIB:
        return ""
    try:
        # 16cm x 8cm at 150dpi for clean A4 output
        fig, ax = plt.subplots(figsize=(6.3, 3.15), dpi=150)
        fig.patch.set_facecolor("white")
        ax.set_facecolor("white")

        palette = _generate_palette(accent, len(labels))

        if chart_type == "pie":
            ax.pie(
                values,
                labels=labels,
                colors=palette,
                autopct="%1.1f%%",
                startangle=90,
                textprops={"fontsize": 8},
            )
        elif chart_type == "line":
            ax.plot(
                labels,
                values,
                color=accent,
                linewidth=2,
                marker="o",
                markersize=5,
            )
            ax.tick_params(axis="x", rotation=30, labelsize=8)
            ax.tick_params(axis="y", labelsize=8)
        elif chart_type == "horizontal_bar":
            y_pos = range(len(labels))
            ax.barh(y_pos, values, color=palette)
            ax.set_yticks(y_pos)
            ax.set_yticklabels(labels, fontsize=8)
            ax.tick_params(axis="x", labelsize=8)
            ax.invert_yaxis()
        else:
            # Default: vertical bar
            x_pos = range(len(labels))
            ax.bar(x_pos, values, color=palette)
            ax.set_xticks(x_pos)
            ax.set_xticklabels(labels, fontsize=8, rotation=30, ha="right")
            ax.tick_params(axis="y", labelsize=8)

        if title:
            ax.set_title(title, fontsize=10, fontweight="bold", pad=10)

        # Readable number formatting (no scientific notation like 1e6)
        if chart_type not in ("pie",):
            from matplotlib.ticker import FuncFormatter
            def _fmt_number(x, _pos):
                if abs(x) >= 1_000_000:
                    return f"{x/1_000_000:.1f} mil."
                if abs(x) >= 1_000:
                    return f"{x/1_000:.0f} tis."
                return f"{x:.0f}"
            ax.yaxis.set_major_formatter(FuncFormatter(_fmt_number))
            if chart_type == "horizontal_bar":
                ax.xaxis.set_major_formatter(FuncFormatter(_fmt_number))

        # Clean styling: remove top/right spines, no grid clutter
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        if chart_type != "pie":
            ax.spines["left"].set_linewidth(0.5)
            ax.spines["bottom"].set_linewidth(0.5)

        fig.tight_layout()

        buf = io.BytesIO()
        fig.savefig(buf, format="png", bbox_inches="tight", facecolor="white")
        plt.close(fig)
        buf.seek(0)
        return base64.b64encode(buf.read()).decode()
    except Exception as exc:
        logger.warning("Chart rendering failed: %s", exc)
        if "fig" in dir():
            try:
                plt.close(fig)  # type: ignore[possibly-undefined]
            except Exception:
                pass
        return ""


def _should_chart_table(headers: list[str], data_rows: list[list[str]]) -> tuple[bool, str]:
    """Decide if a table should have a chart, and which type.

    Based on data visualization best practices:
    - Bar chart: comparing discrete categories (cities, products, modes)
    - Horizontal bar: comparing when labels are long (>15 chars average)
    - Line chart: data over time (years, months, dates in first column)
    - Pie chart: composition/parts of a whole (max 6 slices, has % or podil)
    - NO chart: property tables, attribute lists, mixed non-comparable data,
      tables with <3 rows, tables where values are IDs/years/codes

    Returns (should_chart, chart_type) where chart_type is bar/horizontal_bar/line/pie.

    References:
    - https://www.datawrapper.de/blog/chart-types-guide
    - https://eazybi.com/blog/data-visualization-and-chart-types
    - https://www.atlassian.com/data/charts/essential-chart-types-for-data-visualization
    """
    if len(data_rows) < 3:
        return False, ""

    headers_lower = [h.lower() for h in headers]

    # NEVER chart these - property/attribute tables
    skip_keywords = {
        "popis", "description", "typ", "type", "nazev", "název", "name",
        "adresa", "address", "kontakt", "contact", "odkaz", "link", "url",
        "poznamka", "poznámka", "note", "moznost", "možnost", "option",
        "parametr", "parameter", "stanice", "station", "rok", "year",
        "vyrobce", "výrobce", "manufacturer", "model", "serie", "séria",
        "prestup", "přestup", "transfer", "provozovatel", "operator",
    }

    skip_count = sum(1 for h in headers_lower if any(k in h for k in skip_keywords))
    if skip_count >= len(headers) // 2:
        return False, ""

    # Check if first column contains years/dates -> line chart
    time_pattern = re.compile(r"^(19|20)\d{2}$|^\d{4}[-/]|^Q[1-4]|^(led|úno|bře|dub|kvě|čer|srp|zář|říj|lis|pro|jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)", re.IGNORECASE)
    time_count = sum(1 for row in data_rows if time_pattern.match(row[0].strip()))
    if time_count >= len(data_rows) * 0.7:
        return True, "line"

    # Headers that indicate COMPARABLE metrics worth charting
    metric_keywords = {
        "počet", "pocet", "count", "celkem", "total",
        "podíl", "podil", "%", "procent",
        "mld", "mil", "tis", "kč", "kc", "eur", "usd", "czk",
        "náklady", "naklady", "cost", "cena", "price",
        "délka", "delka", "km", "length",
        "kapacita", "capacity", "cestující", "cestujici", "passengers",
        "přeprava", "preprava", "výkon", "vykon", "objem", "volume",
        "spokojenost", "satisfaction", "score", "index", "rate",
        "emise", "emission", "spotřeba", "spotreba", "consumption",
    }

    # At least one value-column header must suggest a metric
    has_metric = any(
        any(k in h for k in metric_keywords)
        for h in headers_lower[1:]
    )
    if not has_metric:
        return False, ""

    # Check if values are actually comparable numbers (not IDs, years, codes)
    first_values = []
    for row in data_rows:
        if len(row) > 1:
            cleaned = row[1].replace(",", "").replace(" ", "").replace("\xa0", "")
            cleaned = re.sub(r"[%$€]", "", cleaned)
            try:
                first_values.append(float(cleaned))
            except ValueError:
                pass

    if len(first_values) < 3:
        return False, ""

    # If all values are years (1900-2100), don't chart
    if all(1900 <= v <= 2100 for v in first_values):
        return False, ""

    # If values have very low variance (all nearly same), skip
    if max(first_values) > 0 and min(first_values) / max(first_values) > 0.95:
        return False, ""

    # Composition (% or podil) -> pie chart (max 6 slices)
    pct_keywords = {"%", "podíl", "podil", "procent", "share"}
    if any(any(k in h for k in pct_keywords) for h in headers_lower[1:]):
        if len(data_rows) <= 6:
            return True, "pie"

    # Long labels -> horizontal bar
    avg_label_len = sum(len(row[0]) for row in data_rows) / len(data_rows)
    if avg_label_len > 15:
        return True, "horizontal_bar"

    return True, "bar"


def _auto_charts_from_tables(html: str, accent: str) -> str:
    """Detect HTML tables with numeric data and inject chart images below them.

    Only generates charts for tables that represent comparable data (costs,
    counts, percentages) - NOT for property/attribute tables. Uses
    _should_chart_table() heuristic to decide.
    """
    if not HAS_MATPLOTLIB:
        return html

    table_re = re.compile(r"(<table[^>]*>.*?</table>)", re.DOTALL | re.IGNORECASE)
    figure_counter = 0
    parts: list[str] = []
    last_end = 0

    for m in table_re.finditer(html):
        parts.append(html[last_end:m.start()])
        table_html = m.group(1)
        parts.append(table_html)
        last_end = m.end()

        # Extract header cells
        th_re = re.compile(r"<th[^>]*>(.*?)</th>", re.DOTALL | re.IGNORECASE)
        headers = [re.sub(r"<[^>]+>", "", h).strip() for h in th_re.findall(table_html)]

        # Extract body rows
        row_re = re.compile(r"<tr[^>]*>(.*?)</tr>", re.DOTALL | re.IGNORECASE)
        td_re = re.compile(r"<td[^>]*>(.*?)</td>", re.DOTALL | re.IGNORECASE)
        rows_html = row_re.findall(table_html)

        data_rows: list[list[str]] = []
        for row_html in rows_html:
            cells = [re.sub(r"<[^>]+>", "", c).strip() for c in td_re.findall(row_html)]
            if cells:
                data_rows.append(cells)

        if not data_rows or not headers or len(headers) < 2:
            continue

        # Smart decision: should this table have a chart? Which type?
        should_chart, chart_type = _should_chart_table(headers, data_rows)
        if not should_chart:
            continue

        labels = [row[0] for row in data_rows]

        # Extract first numeric column values
        values: list[float] = []
        for row in data_rows:
            if len(row) > 1:
                cleaned = row[1].replace(",", "").replace(" ", "").replace("\xa0", "")
                cleaned = re.sub(r"[%$\u20ac]", "", cleaned)
                try:
                    values.append(float(cleaned))
                except ValueError:
                    values.append(0.0)

        if not values:
            continue

        chart_title = headers[1] if len(headers) > 1 else ""
        b64 = _render_chart_image(chart_type, labels, values, chart_title, accent)
        if b64:
            figure_counter += 1
            caption = f"Figure {figure_counter}: {chart_title}" if chart_title else f"Figure {figure_counter}"
            parts.append(
                f'\n<div class="chart">'
                f'<img src="data:image/png;base64,{b64}" alt="{caption}"/>'
                f'<p class="chart-caption">{caption}</p>'
                f"</div>\n"
            )

    parts.append(html[last_end:])
    return "".join(parts)


# ---------------------------------------------------------------------------
# Explicit ```chart``` fenced code block parsing
# ---------------------------------------------------------------------------

def _parse_chart_blocks(html: str, accent: str) -> str:
    """Parse explicit chart code blocks and render them as matplotlib images.

    Supports YAML-like syntax inside ``<pre><code class="language-chart">``
    blocks with keys: type, title, data (key-value pairs).
    Supported types: bar, horizontal_bar, pie, line.
    """
    if not HAS_MATPLOTLIB:
        return html

    chart_pattern = re.compile(
        r'<pre><code class="language-chart">(.*?)</code></pre>',
        re.DOTALL,
    )

    counter_holder = [0]

    def _replace_chart_block(m: re.Match) -> str:
        spec = m.group(1).strip()
        # Unescape HTML entities
        spec = spec.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")

        chart_type = "bar"
        title = ""
        data: dict[str, float] = {}

        # Parse simple YAML-like key: value format
        current_section: str | None = None
        for line in spec.split("\n"):
            line = line.strip()
            if not line:
                continue
            if line.startswith("type:"):
                chart_type = line.split(":", 1)[1].strip()
            elif line.startswith("title:"):
                title = line.split(":", 1)[1].strip()
            elif line.startswith("data:"):
                current_section = "data"
            elif current_section == "data" and ":" in line:
                key, val = line.rsplit(":", 1)
                key = key.strip()
                val_str = val.strip().replace(",", "").replace(" ", "")
                try:
                    data[key] = float(val_str)
                except ValueError:
                    pass

        if not data:
            return m.group(0)

        labels = list(data.keys())
        values = list(data.values())

        b64 = _render_chart_image(chart_type, labels, values, title, accent)
        if not b64:
            return m.group(0)

        counter_holder[0] += 1
        caption = f"Figure {counter_holder[0]}: {title}" if title else f"Figure {counter_holder[0]}"
        return (
            f'<div class="chart">'
            f'<img src="data:image/png;base64,{b64}" alt="{caption}"/>'
            f'<p class="chart-caption">{caption}</p>'
            f"</div>"
        )

    return chart_pattern.sub(_replace_chart_block, html)


# ---------------------------------------------------------------------------
# KPI / Metric row parsing
# ---------------------------------------------------------------------------

def _parse_metric_rows(html: str) -> str:
    """Convert ``:::metric val1 | val2 | ...:::`` patterns into styled KPI boxes.

    Each segment is split by ``|``. The numeric/bold part becomes the value,
    and the remaining text becomes the label.
    """
    # Match both in raw HTML paragraphs and standalone
    pattern = re.compile(r":::metric\s+(.*?):::", re.DOTALL)

    def _replace_metric(m: re.Match) -> str:
        raw = m.group(1).strip()
        # Strip any enclosing <p>...</p> or <br/> tags
        raw = re.sub(r"<[^>]+>", " ", raw).strip()
        segments = [s.strip() for s in raw.split("|") if s.strip()]
        if not segments:
            return m.group(0)

        boxes: list[str] = []
        for seg in segments:
            # Split: first token(s) that look like a number/value, rest is label
            # Heuristic: value is everything up to the first letter-only word
            parts = seg.split(None, 1)
            if not parts:
                continue
            # Try to identify the numeric value portion
            value_parts: list[str] = []
            label_parts: list[str] = []
            found_label = False
            for word in seg.split():
                cleaned = word.replace(",", "").replace(".", "").replace("+", "").replace("%", "")
                if not found_label and (cleaned.isdigit() or word in ("mld.", "mil.", "tis.", "km", "ks", "Kc", "CZK", "EUR", "USD")):
                    value_parts.append(word)
                else:
                    found_label = True
                    label_parts.append(word)
            value = " ".join(value_parts) if value_parts else parts[0]
            label = " ".join(label_parts) if label_parts else ""
            boxes.append(
                f'<div class="metric-box">'
                f'<div class="metric-value">{value}</div>'
                f'<div class="metric-label">{label}</div>'
                f"</div>"
            )

        return f'<div class="metric-row">{"".join(boxes)}</div>'

    # Handle the pattern inside <p> tags as well
    result = re.sub(r"<p>\s*" + pattern.pattern + r"\s*</p>", lambda m: _replace_metric(m), html, flags=re.DOTALL)
    result = pattern.sub(_replace_metric, result)
    return result


# ---------------------------------------------------------------------------
# Callout box parsing
# ---------------------------------------------------------------------------

def _parse_callout_boxes(html: str) -> str:
    """Convert ``:::info``, ``:::warning``, ``:::success`` blocks into styled callouts.

    Blocks are delimited by ``:::type`` and ``:::`` on their own lines.
    """
    # These may appear as <p>:::info</p> ... <p>:::</p> in the HTML
    callout_types = ("info", "warning", "success")

    for ctype in callout_types:
        # Pattern: opening tag, content, closing tag - handle various HTML wrapping
        pattern = re.compile(
            r"(?:<p>)?\s*:::" + ctype + r"\s*(?:</p>)?\s*"
            r"(.*?)"
            r"(?:<p>)?\s*:::\s*(?:</p>)?",
            re.DOTALL,
        )

        def _make_replacer(ct: str):  # noqa: E301
            def _replace(m: re.Match) -> str:
                content = m.group(1).strip()
                # Wrap bare text in <p> if needed
                if not content.startswith("<"):
                    content = f"<p>{content}</p>"
                return f'<div class="callout callout-{ct}">{content}</div>'
            return _replace

        html = pattern.sub(_make_replacer(ctype), html)

    return html


# ---------------------------------------------------------------------------
# Styled divider parsing
# ---------------------------------------------------------------------------

def _parse_dividers(html: str) -> str:
    r"""Convert ``---{Section Break}---`` patterns into styled divider elements.

    These can appear as literal text or wrapped in ``<p>`` or ``<hr>`` tags.
    """
    # Match inside <p> tags or standalone.
    # The smarty markdown extension converts --- to &mdash; so handle both.
    dash = r"(?:---|&mdash;|\u2014)"
    pattern = re.compile(
        r"(?:<p>)?\s*" + dash + r"\{(.+?)\}" + dash + r"\s*(?:</p>)?",
        re.DOTALL,
    )

    def _replace_divider(m: re.Match) -> str:
        text = re.sub(r"<[^>]+>", "", m.group(1)).strip()
        return f'<div class="styled-divider"><span>{text}</span></div>'

    return pattern.sub(_replace_divider, html)


# ---------------------------------------------------------------------------
# Pre-markdown transformation (runs on raw markdown BEFORE conversion)
# ---------------------------------------------------------------------------

def _preprocess_markdown(text: str) -> str:
    """Transform custom syntax elements in raw markdown before HTML conversion.

    This handles patterns that would be mangled by the markdown parser,
    such as :::metric and :::callout blocks which need to pass through
    to post-processing as recognizable patterns.
    """
    # No transformations needed currently - the patterns survive markdown
    # conversion inside <p> tags which the post-processors handle.
    return text


