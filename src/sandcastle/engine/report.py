def _markdown_to_html(text: str) -> str:
    """Convert Markdown content to HTML.

    Uses the ``markdown`` library with tables, fenced_code, and toc
    extensions when available, otherwise falls back to a basic regex
    converter.
    """
    if HAS_MARKDOWN:
        return md_lib.markdown(
            text,
            extensions=["tables", "fenced_code", "toc", "smarty", "nl2br"],
        )
    # Minimal fallback: headings, bold, italic, code blocks, paragraphs
    html = text

    # Fenced code blocks (```lang ... ```)
    def _replace_code_block(m: re.Match) -> str:
        lang = m.group(1) or ""
        code = m.group(2)
        cls = f' class="language-{lang}"' if lang else ""
        escaped = code.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        return f"<pre><code{cls}>{escaped}</code></pre>"

    html = re.sub(r"^```(\w*)\n(.*?)^```", _replace_code_block, html, flags=re.MULTILINE | re.DOTALL)

    html = re.sub(r"^#### (.+)$", r"<h4>\1</h4>", html, flags=re.MULTILINE)
    html = re.sub(r"^### (.+)$", r"<h3>\1</h3>", html, flags=re.MULTILINE)
    html = re.sub(r"^## (.+)$", r"<h2>\1</h2>", html, flags=re.MULTILINE)
    html = re.sub(r"^# (.+)$", r"<h1>\1</h1>", html, flags=re.MULTILINE)
    html = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", html)
    html = re.sub(r"\*(.+?)\*", r"<em>\1</em>", html)
    # Wrap remaining bare lines in <p>
    lines = html.split("\n")
    result: list[str] = []
    for line in lines:
        stripped = line.strip()
        if not stripped:
            result.append("")
        elif stripped.startswith("<"):
            result.append(stripped)
        else:
            result.append(f"<p>{stripped}</p>")
    return "\n".join(result)


